# KBC with ques, money and safe levels, quit option

def login_player():
    print("=" * 42)
    print("          KAUN BANEGA CROREPATI")
    print("=" * 42)

    while True:
        player_name = input("Enter your player name to log in: ").strip()
        if player_name:
            return player_name
        print("Player name cannot be empty. Please try again.")


player_name = login_player()

ques = [
["What is the capital of India?", "A. Mumbai", "B. Delhi", "C. Kolkata", "D. Chennai", "B"],
["Which language is used in Data Science most commonly?", "A. Java", "B. Python", "C. C++", "D. HTML", "B"],
["Who is known as the Father of Computer?", "A. Alan Turing", "B. Charles Babbage", "C. Bill Gates", "D. Elon Musk", "B"],
["Which keyword is used to define a function in Python?", "A. func", "B. define", "C. def", "D. function", "C"],
["Which planet is known as the Red Planet?", "A. Earth", "B. Mars", "C. Jupiter", "D. Venus", "B"],
["What does CPU stand for?", "A. Central Processing Unit", "B. Computer Processing Unit", "C. Central Power Unit", "D. Control Processing Unit", "A"],
["Which data type is used to store text in Python?", "A. int", "B. float", "C. str", "D. bool", "C"],
["Which operator is used for exponentiation in Python?", "A. ^", "B. **", "C. *", "D. //", "B"],
["Which of the following is a loop in Python?", "A. repeat", "B. loop", "C. for", "D. iterate", "C"],
["Which library is used for data analysis in Python?", "A. NumPy", "B. Pandas", "C. Matplotlib", "D. TensorFlow", "B"]
]

money = [1000, 2000, 5000, 10000, 20000, 40000, 80000, 160000, 320000, 1000000]

safe_levels = [10000, 320000]

print(f"\n🎯 Welcome to KBC, {player_name}!")
print("Type A/B/C/D to answer or QUIT to exit\n")

winnings = 0
safe_amount = 0

for i, q in enumerate(ques):

    print("\n" + q[0])
    print(q[1])
    print(q[2])
    print(q[3])
    print(q[4])

    # input validation loop
    while True:
        ans = input("Enter your answer: ").upper()

        if ans == "QUIT":
            print(f"{player_name}, you quit with ₹{winnings}")
            exit()

        if ans not in ["A", "B", "C", "D"]:
            print("Invalid input! Try again.")
            continue

        break

    # ✅ correct answer
    if ans == q[-1]:
        winnings = money[i]
        print(f"✅ Correct! You won ₹{winnings}")

        # 🔒 safe level check
        if winnings in safe_levels:
            safe_amount = winnings
            print("🔒 Safe level reached!")

    # ❌ wrong answer
    else:
        print("❌ Wrong Answer")
        print(f"You take home ₹{safe_amount}")
        break

# 🎉 if all correct
else:
    print(f"🎉 Congratulations, {player_name}! You won ₹1,000,000")
